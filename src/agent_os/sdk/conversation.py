"""에이전트가 컨텍스트로 받는 대화의 값. 자기 대화 요약과 그 뒤 자기 교환들이다(ADR 0022).

대화는 새 실행이 같은 주체의 끝난 실행을 이어 가며 생기는 실행들의 고리이고(용어집 "대화"), 저장되지
않고 트레이스에서 파생된다. 에이전트는 고리 전체가 아니라 고리에서 자기가 처리한 교환(요청과 출력)과
자기 대화 요약만 받는다. 다른 에이전트의 교환은 그 에이전트의 프롬프트와 도구 결과 위에서 나온
출력이라 넘기지 않는다.

**신뢰 경계.** 요약과 교환의 요청은 최종 사용자의 입력과 같은 신뢰 수준이다. 요약은 요청과 출력을
같은 모델이 섞어 쓴 글이라, 요청에 심은 지시나 주장이 출처가 흐려진 채 "에이전트의 앞선 출력"처럼
실릴 수 있다. 에이전트는 이것을 지시가 아니라 데이터로 프롬프트에 엮는다. 런타임은 `llm()` 의
프롬프트에 이것을 붙이지 않는다. 프롬프트는 에이전트가 짓는다.

값은 불변이고 런타임이 에이전트를 부르기 전에 정해 실행 안에서 바뀌지 않는다. 재개해도 같은 값이다.
재생이 에이전트가 이것을 엮은 프롬프트를 대조하기 때문이다(ADR 0009).
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Exchange:
    """대화 안의 실행 하나가 남긴 요청과 출력. 도구 호출, 도구 결과, 실행 식별자, 시각은 없다."""

    request: str
    output: str


@dataclass(frozen=True)
class Conversation:
    """한 에이전트가 대화에서 아는 것. 가장 가까운 자기 대화 요약과 그 뒤 자기 교환들이다.

    `summary` 는 그 에이전트의 가장 가까운 대화 요약이고 없으면 None 이다. `exchanges` 는 그 요약
    뒤(요약이 없으면 고리의 처음부터)의 자기 교환이고 오래된 것부터다. 이어 가지 않은 실행에서는
    요약이 없고 열이 비어 있다. 신뢰 경계는 모듈 독스트링이다.
    """

    summary: str | None
    exchanges: tuple[Exchange, ...]
