"""경로가 어느 면의 것인가. 접두사 비교는 여기 한 곳이다(ADR 0015·0023).

인증의 접두사 표와 예외 표의 면 판정이 같은 비교를 쓴다. 최종 사용자 면에만 거는 CORS 분기도 이
비교를 쓰기로 했다(그 분기는 end-user-channel 티켓 04 가 들인다). 각자 비교하면 어느 하나가 어긋나는
날 같은 경로가 한쪽에서는 최종 사용자 면이고 다른 쪽에서는 아니게 된다 — 토큰은 서명 토큰으로
열었는데 에러는 운영자 면의 원문으로 나가는 식이다.
"""

from __future__ import annotations


def is_under(path: str, prefix: str) -> bool:
    """경로가 접두사 아래인가(질의). 경로 조각 단위로 본다.

    `/runs` 는 `/runs` 와 `/runs/…` 에 걸리고 `/runsx` 에는 걸리지 않는다 — 문자열 접두사면 이름이
    우연히 겹친 경로가 다른 면으로 넘어간다. 미들웨어와 라우팅이 같은 경로 문자열을 보므로 이 분류와
    라우트가 엇갈릴 길은 없다. 접두사들은 서로를 품지 않는다고 본다. 품는 표가 생기면 어느 쪽이
    이기는지를 그 표를 넘기는 쪽이 테스트와 함께 정한다.
    """
    return path == prefix or path.startswith(f"{prefix}/")
