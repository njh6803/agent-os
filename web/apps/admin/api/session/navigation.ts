// 화면을 통째로 옮기는 자리 하나. 로그인 화면으로 보내거나 로그인 뒤에 보던 화면으로 돌려보낼 때 지난다. 페이지 시험은
// 이 모듈을 가짜로 바꿔 어느 주소로 보냈는지를 본다(jsdom 의 `location.assign` 은 이동하지 않고 에러를 콘솔에 찍는다).
// 주소를 풀지 못하면 옮기지 않는다는 판단은 부르는 쪽(`address.ts`)이 한다. 여기는 받은 주소로 옮기기만 한다.

/** 지금 탭을 그 주소로 옮긴다. 새로 불러오므로 앞 계정의 화면 상태(SWR 캐시 따위)가 남지 않는다. */
export function goTo(href: string): void {
  location.assign(href);
}
